def write(name, svg):
    if svg is None:
        return
    os.makedirs(OUT, exist_ok=True)
    path = os.path.join(OUT, name)
    old = None
    if os.path.exists(path):
        with open(path, encoding="utf-8") as f:
            old = f.read()
    if old == svg:
        log(f"  = {path} unchanged")
        return
    with open(path, "w", encoding="utf-8") as f:
        f.write(svg)
    log(f"  + {path} written ({len(svg):,} bytes)")


