def log(m):
    print(m, flush=True)


def die(m):
    print(f"::error::{m}", file=sys.stderr, flush=True)
    sys.exit(1)


def esc(s):
    return (str(s).replace("&", "&amp;").replace("<", "&lt;")
            .replace(">", "&gt;").replace('"', "&quot;"))


def rest(path, optional=False):
    req = urllib.request.Request(
        f"https://api.github.com{path}",
        headers={"Accept": "application/vnd.github+json",
                 "User-Agent": "profile-card-generator",
                 **({"Authorization": f"Bearer {TOKEN}"} if TOKEN else {})},
    )
    try:
        with urllib.request.urlopen(req, timeout=30) as r:
            return json.load(r)
    except Exception as e:
        if optional:
            log(f"  ! {type(e).__name__} on {path} — skipping")
            return None
        die(f"{type(e).__name__} on {path}: {e}")


def graphql(query, variables):
    if not TOKEN:
        return None
    req = urllib.request.Request(
        "https://api.github.com/graphql",
        data=json.dumps({"query": query, "variables": variables}).encode(),
        headers={"Authorization": f"Bearer {TOKEN}",
                 "Content-Type": "application/json",
                 "User-Agent": "profile-card-generator"},
    )
    try:
        with urllib.request.urlopen(req, timeout=30) as r:
            body = json.load(r)
        if "errors" in body:
            log(f"  ! GraphQL: {body['errors'][0].get('message')}")
            return None
        return body.get("data")
    except Exception as e:
        log(f"  ! GraphQL unavailable ({type(e).__name__}) — falling back to REST")
        return None


# --------------------------------------------------------------------------- data

GQL = """
query($login:String!) {
  user(login:$login) {
    followers { totalCount }
    following { totalCount }
    repositories(first:1, ownerAffiliations:OWNER) { totalCount }
    pullRequests { totalCount }
    issues { totalCount }
    contributionsCollection {
      totalCommitContributions
      restrictedContributionsCount
      contributionCalendar {
        totalContributions
        weeks { contributionDays { contributionCount date } }
      }
    }
    repositoriesContributedTo(contributionTypes:[COMMIT,PULL_REQUEST,ISSUE,REPOSITORY]) {
      totalCount
    }
  }
}
"""


def gather():
    d = {"login": USER}

    user = rest(f"/users/{USER}")
    d["followers"] = user.get("followers", 0)
    d["following"] = user.get("following", 0)
    d["public_repos"] = user.get("public_repos", 0)
    d["name"] = user.get("name") or USER

    repos, page = [], 1
    while page <= 10:
        batch = rest(f"/users/{USER}/repos?per_page=100&page={page}&sort=pushed")
        if not batch:
            break
        repos.extend(batch)
        if len(batch) < 100:
            break
        page += 1
    owned = [r for r in repos if not r.get("fork")]
    d["stars"] = sum(r.get("stargazers_count", 0) for r in owned)
    d["forks"] = sum(r.get("forks_count", 0) for r in owned)

    # language byte totals across all non-fork repos
    langs = Counter()
    for r in owned:
        data = rest(f"/repos/{USER}/{r['name']}/languages", optional=True)
        if data:
            langs.update(data)
    d["languages"] = langs

    g = graphql(GQL, {"login": USER})
    if g and g.get("user"):
        u = g["user"]
        cc = u["contributionsCollection"]
        d["commits"] = cc["totalCommitContributions"] + cc.get("restrictedContributionsCount", 0)
        d["prs"] = u["pullRequests"]["totalCount"]
        d["issues"] = u["issues"]["totalCount"]
        d["contributed"] = u["repositoriesContributedTo"]["totalCount"]
        d["total_contributions"] = cc["contributionCalendar"]["totalContributions"]
        days = [(day["date"], day["contributionCount"])
                for w in cc["contributionCalendar"]["weeks"]
                for day in w["contributionDays"]]
        d["calendar"] = [c for _, c in days]
        d["calendar_days"] = days
    else:
        log("  (no token — commit/PR/issue counts unavailable, card adapts)")
        d.update(commits=None, prs=None, issues=None, contributed=None,
                 total_contributions=None, calendar=[], calendar_days=[])

    log(f"Gathered: {len(owned)} repos, {d['stars']} stars, "
        f"{len(langs)} languages, {len(d['calendar'])} contribution days")
    return d


